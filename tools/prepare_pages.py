#!/usr/bin/env python3
"""
Prepare hadistory pages for the Pico version.

Reads the shared stories (stories/<story>/txt/pN.txt + stories/<story>/img/pN.png) and
writes, for each page, a JPEG illustration and the page text. The Pico firmware composes
the page itself (illustration on top, text below in its bitmap font, dithered to the
7 colours of the Inky Impression), the same way it composes the pages of its AI mode.

Output, one folder per story in <out>/stories/<story>/:
  pN.jpg   illustration, square, --size pixels (default 448, the width of the display),
           JPEG quality --quality (default 85)
  pN.txt   page text, UTF-8, newlines turned into spaces

Embedded (flash) variant of the Pico firmware (--embed DIR): also writes
  DIR/stories_data.S   one .incbin per JPEG and per text (NUL terminated)
  DIR/stories_table.c  catalogue of the embedded stories for pico/src/storage_flash.cpp

Usage:
  python3 tools/prepare_pages.py                 # all stories -> tools/out/
  python3 tools/prepare_pages.py --story story_3 # one story
  python3 tools/prepare_pages.py --embed DIR     # plus the files for the flash build
  python3 tools/prepare_pages.py --help
"""

import argparse
import re
import sys
from pathlib import Path

from PIL import Image, ImageEnhance

REPO_ROOT = Path(__file__).resolve().parent.parent

IMAGE_SIZE = 448          # the display is 448 px wide in portrait
IMAGE_QUALITY = 85
IMAGE_SHARPNESS = 1.2     # as pi/omni-epd.ini [Image Enhancements] sharpness


def natural_key(path):
    return [int(s) if s.isdigit() else s for s in re.split(r"(\d+)", path.name)]


def list_pages(story_dir):
    """Return [(page_number, txt_path, img_path), ...] sorted by page number."""
    txt_dir = story_dir / "txt"
    img_dir = story_dir / "img"
    pages = []
    for txt in sorted(txt_dir.glob("p*.txt"), key=natural_key):
        m = re.fullmatch(r"p(\d+)\.txt", txt.name)
        if not m:
            continue
        n = int(m.group(1))
        img = img_dir / f"p{n}.png"
        if not img.exists():
            print(f"  WARNING: {img} missing, page {n} skipped", file=sys.stderr)
            continue
        pages.append((n, txt, img))
    return pages


def prepare_image(img_path, size, quality, sharpness, out_path):
    im = Image.open(img_path).convert("RGB")
    im = im.resize((size, size), Image.LANCZOS)
    if sharpness != 1.0:
        im = ImageEnhance.Sharpness(im).enhance(sharpness)
    im.save(out_path, "JPEG", quality=quality, optimize=True, progressive=False)


def prepare_text(txt_path, out_path):
    text = txt_path.read_text(encoding="utf-8").replace("\r", "").replace("\n", " ").strip()
    text = re.sub(r"\s{2,}", " ", text)
    out_path.write_text(text, encoding="utf-8")


def write_embedded(prepared, embed_dir):
    """Write the assembly and C files that embed the prepared pages in the firmware.

    prepared: [(story_name, [(jpg_path, txt_path), ...]), ...] in page order.
    """
    embed_dir.mkdir(parents=True, exist_ok=True)
    asm = ["// Generated by tools/prepare_pages.py, do not edit.",
           '    .section .rodata.hadistory_stories, "a"']
    c = ["// Generated by tools/prepare_pages.py, do not edit.",
         '#include "stories_embedded.h"', ""]
    table = []
    for story, pages in prepared:
        entries = []
        for n, (jpg, txt) in enumerate(pages, start=1):
            sym = f"hadistory_{story}_p{n}"
            asm += ["    .balign 4", f"    .global {sym}_jpg", f"{sym}_jpg:",
                    f'    .incbin "{jpg.resolve()}"',
                    f"    .global {sym}_txt", f"{sym}_txt:",
                    f'    .incbin "{txt.resolve()}"', "    .byte 0"]
            c.append(f"extern const uint8_t {sym}_jpg[];")
            c.append(f"extern const char {sym}_txt[];")
            entries.append(f"{{ {sym}_jpg, {jpg.stat().st_size}, {sym}_txt }}")
        c.append(f"static const embedded_page_t {story}_pages[] = {{ " + ", ".join(entries) + " };")
        table.append(f'    {{ "{story}", {len(pages)}, {story}_pages }},')
    c += ["", "const embedded_story_t embedded_stories[] = {", *table, "};",
          f"const int embedded_story_count = {len(prepared)};", ""]
    (embed_dir / "stories_data.S").write_text("\n".join(asm) + "\n")
    (embed_dir / "stories_table.c").write_text("\n".join(c))
    print(f"embedded: {embed_dir}/stories_data.S, stories_table.c")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--stories", type=Path, default=REPO_ROOT / "stories",
                        help="stories folder (default: <repo>/stories)")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "tools" / "out",
                        help="output folder (default: <repo>/tools/out)")
    parser.add_argument("--story", action="append",
                        help="only prepare this story (repeatable)")
    parser.add_argument("--size", type=int, default=IMAGE_SIZE,
                        help=f"illustration side in pixels (default {IMAGE_SIZE})")
    parser.add_argument("--quality", type=int, default=IMAGE_QUALITY,
                        help=f"JPEG quality 1-95 (default {IMAGE_QUALITY})")
    parser.add_argument("--sharpness", type=float, default=IMAGE_SHARPNESS,
                        help=f"illustration sharpness factor (default {IMAGE_SHARPNESS})")
    parser.add_argument("--embed", type=Path, metavar="DIR",
                        help="also write stories_data.S and stories_table.c into DIR "
                             "(flash variant of the Pico firmware)")
    args = parser.parse_args()

    story_dirs = sorted((d for d in args.stories.iterdir() if (d / "txt").is_dir()),
                        key=natural_key)
    if args.story:
        story_dirs = [d for d in story_dirs if d.name in args.story]
        missing = set(args.story) - {d.name for d in story_dirs}
        if missing:
            sys.exit(f"story not found: {', '.join(sorted(missing))}")

    total = 0
    total_bytes = 0
    prepared = []
    for story_dir in story_dirs:
        pages = list_pages(story_dir)
        if not pages:
            print(f"{story_dir.name}: no pages, skipped")
            continue
        out_dir = args.out / "stories" / story_dir.name
        out_dir.mkdir(parents=True, exist_ok=True)
        written = []
        for n, txt, img in pages:
            jpg_out = out_dir / f"p{n}.jpg"
            txt_out = out_dir / f"p{n}.txt"
            prepare_image(img, args.size, args.quality, args.sharpness, jpg_out)
            prepare_text(txt, txt_out)
            written.append((jpg_out, txt_out))
            total += 1
            total_bytes += jpg_out.stat().st_size + txt_out.stat().st_size
        print(f"{story_dir.name}: {len(pages)} pages")
        prepared.append((story_dir.name, written))

    print(f"done: {total} pages, {total_bytes / 1e6:.1f} MB in {args.out}")
    if args.embed:
        write_embedded(prepared, args.embed)


if __name__ == "__main__":
    main()
